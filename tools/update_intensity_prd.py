def replace_start(doc, prefix, text):
    for p in doc.paragraphs:
        if p.text.startswith(prefix):
            for r in p.runs:
                r.text = ''
            if p.runs:
                p.runs[0].text = text
            else:
                p.add_run(text)
            return True
    return False


