def replace_paragraphs(doc: Document, replacements: dict[str, str]) -> None:
    hits = {key: 0 for key in replacements}
    for paragraph in doc.paragraphs:
        if paragraph.text in replacements:
            old = paragraph.text
            paragraph.text = replacements[old]
            hits[old] += 1
    missing = [key for key, count in hits.items() if count != 1]
    if missing:
        raise RuntimeError(f"paragraph replacement mismatch: {missing}; hits={hits}")


def set_cell_text(cell, value: str) -> None:
    cell.text = value


