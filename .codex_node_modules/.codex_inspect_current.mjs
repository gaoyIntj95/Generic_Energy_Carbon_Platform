import fs from "node:fs/promises";
import { FileBlob, SpreadsheetFile } from "@oai/artifact-tool";

const inputPath = "C:/Users/340710/Desktop/曲靖零碳园区项目/用能单元与能源管理配置表.xlsx";
const outDir = "D:/Project/Generic_Energy_Carbon_Platform/outputs/inspect-current";
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(inputPath));
console.log((await wb.inspect({kind:"workbook,sheet,table", maxChars:16000, tableMaxRows:20, tableMaxCols:12, tableMaxCellChars:200})).ndjson);
for (const s of wb.worksheets.items) {
  console.log(`SHEET:${s.name}`);
  console.log((await wb.inspect({kind:"region", sheetId:s.name, range:"A1:Z120", maxChars:30000})).ndjson);
  const p = await wb.render({sheetName:s.name, autoCrop:"all", scale:1, format:"png"});
  await fs.mkdir(outDir, {recursive:true});
  await fs.writeFile(`${outDir}/${s.name.replaceAll(/[\\/:*?"<>|]/g,"_")}.png`, new Uint8Array(await p.arrayBuffer()));
}
