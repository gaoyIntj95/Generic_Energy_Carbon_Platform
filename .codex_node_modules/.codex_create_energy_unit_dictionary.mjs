function writeSheet(sheet, range, values, widths) {
  sheet.getRange(range).values = values;
  const match = range.match(/^([A-Z]+)(\d+):([A-Z]+)(\d+)$/);
  const startCol = match[1], startRow = Number(match[2]), endCol = match[3];
  const endRow = startRow + values.length - 1;
  sheet.getRange(`${startCol}${startRow}:${endCol}${endRow}`).format = body;
  sheet.getRange(`${startCol}${startRow}:${endCol}${startRow}`).format = header;
  sheet.getRange(`${startCol}${startRow}:${endCol}${endRow}`).format.borders = borders;
  sheet.getRange(`${startCol}${startRow}:${endCol}${endRow}`).format.rowHeight = 28;
  widths.forEach(([col, width]) => sheet.getRange(`${col}:${col}`).format.columnWidth = width);
  sheet.freezePanes.freezeRows(startRow);
  sheet.showGridLines = false;
}

