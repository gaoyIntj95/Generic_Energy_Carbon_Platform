import fs from "node:fs/promises";
import { FileBlob, SpreadsheetFile } from "@oai/artifact-tool";
const dir = "D:/Project/Generic_Energy_Carbon_Platform/outputs/20260911-energy-unit-dictionary";
const path = `${dir}/用能单元页面-关系树与字典表.xlsx`;
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(path));
for (const s of wb.worksheets.items) {
  const p = await wb.render({sheetName:s.name, autoCrop:"all", scale:1, format:"png"});
  await fs.writeFile(`${dir}/${s.name}.png`, new Uint8Array(await p.arrayBuffer()));
}
console.log("RENDERED");
