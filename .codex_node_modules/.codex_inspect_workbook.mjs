import fs from "node:fs/promises";
import { FileBlob, SpreadsheetFile } from "@oai/artifact-tool";

const inputPath = "C:/Users/340710/Desktop/曲靖零碳园区项目/能源监测与分析-功能清单.xlsx";
const outDir = "C:/Users/340710/.codex/visualizations/2026/09/11/01a08f3d-2d13-7482-8614-19fe3c6b7aa2";
const wb = await SpreadsheetFile.importXlsx(await FileBlob.load(inputPath));
console.log((await wb.inspect({kind:"workbook,sheet,table", maxChars:12000, tableMaxRows:30, tableMaxCols:12, tableMaxCellChars:200})).ndjson);
for (const s of wb.worksheets.items) {
  console.log(`SHEET:${s.name}`);
  console.log((await wb.inspect({kind:"region", sheetId:s.name, range:"A1:Z80", maxChars:20000})).ndjson);
  const p = await wb.render({sheetName:s.name, autoCrop:"all", scale:1, format:"png"});
  await fs.writeFile(`${outDir}/${s.name.replaceAll(/[\\/:*?"<>|]/g,"_")}.png`, new Uint8Array(await p.arrayBuffer()));
}
